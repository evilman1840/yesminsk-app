export const attendanceBadge = (count: number) => count >= 10
  ? { emoji: '✨', label: 'В ритме Сходок', range: '10 и больше Сходок' }
  : count >= 5
    ? { emoji: '🎒', label: 'Частый гость', range: '5–9 Сходок' }
    : count >= 2
      ? { emoji: '🚶', label: 'В компании', range: '2–4 Сходки' }
      : { emoji: '👋', label: 'Первая Сходка', range: '1 Сходка' };

