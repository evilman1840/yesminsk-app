export type CrashWho = { me: boolean; gen: string; ins: string };

export const crashText = (who: CrashWho, cause: import('../games/tractors').Cause, other?: CrashWho): string => {
  const subj = who.me ? 'Твой трактор' : `Трактор ${who.gen}`;
  let what: string;
  switch (cause.k) {
    case 'border':
      what = pick(['уехал за МКАД', 'решил, что за МКАДом лучше', 'вылетел на МКАД']);
      break;
    case 'river':
      what = pick(['искупался в Свислочи', 'ушёл рыбачить в Свислочь', 'проверил, глубокая ли Свислочь']);
      break;
    case 'place':
      what = pick([`влетел в ${PLACE_ACC[cause.place]}`, `протаранил ${PLACE_ACC[cause.place]}`, ...PLACE_JOKES[cause.place]]);
      break;
    case 'own':
      what = pick(['заблудился в своей же борозде', 'перепахал сам себя', 'попал в собственную ловушку']);
      break;
    case 'trail':
      what = other?.me
        ? pick(['влетел в твою борозду', 'попался в твою ловушку', 'не заметил твою борозду'])
        : pick([`влетел в борозду ${other?.gen}`, `запутался в борозде ${other?.gen}`, `увяз в борозде ${other?.gen}`]);
      break;
    case 'tractor':
      what = other?.me ? pick(['встретился с тобой лоб в лоб', 'поцеловался с тобой капотами']) : pick([`встретился лоб в лоб с ${other?.ins}`, `поцеловался капотами с ${other?.ins}`]);
      break;
  }
  return `${subj} ${what}`;
};

